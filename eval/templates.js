import { buildFixtures } from './fixtures.js';
import { INTENT_TEMPLATES } from './templates_intent.js';
import { TARGET_TEMPLATES } from './templates_target.js';
import { takeSpread } from './task.js';

const TASKS_PER_TYPE = 30;
const ALL_TEMPLATES = [...INTENT_TEMPLATES, ...TARGET_TEMPLATES];

const buildAllTasks = (fixtures, catalogues) => fixtures.flatMap(fixture => ALL_TEMPLATES.flatMap(buildTasks => buildTasks(fixture, catalogues)));

const selectByType = (all_tasks, task_type) => {
	const type_tasks = all_tasks.filter(task => task.task_type === task_type);
	const nominal_tasks = type_tasks.filter(task => !task.edge);
	const edge_tasks = type_tasks.filter(task => task.edge);
	return [...takeSpread(nominal_tasks, TASKS_PER_TYPE / 2), ...takeSpread(edge_tasks, TASKS_PER_TYPE / 2)];
};

/**
 * Builds the scored task set. Every task is generated by a template from a
 * fixture, and every expected value is derived by code, so adding a capture or a
 * transform widens coverage without a hand-written label. Selection is an even
 * spread over the generated pool, half nominal and half edge per type, and it
 * preserves generation order so the chr1 and chr8 tasks at the identical region
 * stay adjacent.
 */
export const buildTaskSet = catalogues => {
	const fixtures = buildFixtures();
	const all_tasks = buildAllTasks(fixtures, catalogues);
	const task_types = [...new Set(all_tasks.map(task => task.task_type))];
	return { fixtures, tasks: task_types.flatMap(task_type => selectByType(all_tasks, task_type)) };
};
